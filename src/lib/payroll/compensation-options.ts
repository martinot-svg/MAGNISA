export function customCompensationCode(label: string) {
  const slug = label.normalize("NFD").replace(/[\\u0300-\\u036f]/g, "").toLowerCase()
    .replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  return slug ? `custom_${slug}` : "other_custom";
}
